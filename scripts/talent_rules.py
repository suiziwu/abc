# 各方向专业与课程（课程标签覆盖技能词典）
def classify(title, desc, industry2):
    text = title + ' ' + desc
    for pat, fam in TITLE_RULES:
        if re.search(pat, title):
            if fam == 'IT':
                for ipat, ifam in IT_DETAIL:
                    if re.search(ipat, text):
                        return ifam
                return '全栈/AI应用开发'
            return fam
    fallback = INDUSTRY_FALLBACK.get(industry2, '其他')
    if fallback == 'IT':
        return '全栈/AI应用开发'
    return fallback


def clean(text):
    if not text:
        return ''
    text = re.sub(r'(BOSS直聘|boss|直聘|kanzhun|来自BOSS直聘)', '', text)
    text = re.sub(r'\s+', ' ', text).strip()
    return text


